function getWeekStartDate(weekNum: number): string {
  // Week 1 starts Nov 2, 2026
  const base = Date.UTC(2026, 10, 2); // month 10 = November
  const ms = base + (weekNum - 1) * 7 * 86400000;
  return new Date(ms).toISOString().slice(0, 10);
}

